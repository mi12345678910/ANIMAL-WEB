/**
 * Chinese (Simplified) overlay for the species registry.
 *
 * Keyed by `animal.id` and `behavior.id` rather than replacing the animal
 * files, so the English data stays the single source of truth for everything
 * non-textual — poses, oscillators, camera focus, model paths — and an untranslated
 * field simply falls back to English instead of disappearing.
 *
 * `cues` are matched to the English array **by index**, so the order here must
 * match the order in the animal file. `localizeAnimal` falls back per item, so a
 * short array degrades to English for the remainder rather than dropping cues.
 */

export interface BehaviorTranslation {
  label: string;
  title: string;
  tagline: string;
  /** Same order as the English `cues`. */
  cues: { part: string; text: string }[];
  meaning: string;
  respond: string[];
  avoid?: string;
}

export interface AnimalTranslation {
  name: string;
  blurb: string;
  starterQuestions?: string[];
  behaviors?: Record<string, BehaviorTranslation>;
}

